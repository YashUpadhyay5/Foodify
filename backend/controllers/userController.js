// ============================================================
// USER CONTROLLER - Authentication & Authorization logic
// ============================================================

// Import User MongoDB model
// Used to interact with users collection in MongoDB
import userModel from "../models/userModel.js";

// Import JWT for creating authentication tokens
import jwt from "jsonwebtoken";

// Import bcrypt for password hashing and comparison
import bcrypt from "bcrypt";

// Import validator for validating email format
import validator from "validator";


// ============================================================
// LOGIN USER CONTROLLER
// ============================================================

// Purpose:
// --------
// Authenticates an existing user
// - Verifies email exists in database
// - Compares entered password with hashed password
// - Generates JWT token on successful login
//
// Request Type: POST
// Endpoint: /api/user/login
//
// Request Body:
// -------------
// {
//   "email": "user@example.com",
//   "password": "password123"
// }
//
const loginUser = async function (req, res) {
    
    // Extract email and password from request body
    const { email, password } = req.body;

    // Debug log to verify login attempts
    console.log("Login attempt with email:", email);

    try {
        // Check if user exists with given email
        const user = await userModel.findOne({ email });

        // If user does not exist, return error
        if (!user) {
            return res.json({
                success: false,
                message: "User does not exist"
            });
        }

        // Compare entered password with hashed password in DB
        const isMatch = await bcrypt.compare(password, user.password);

        // If password does not match, return error
        if (!isMatch) {
            return res.json({
                success: false,
                message: "Invalid credentials"
            });
        }

        // Generate JWT token using user ID  auto-generated by MongoDB   after savng user these pass to token in parter as id 
        const token = createToken(user._id);

        // Send success response with token
        res.json({
            success: true,
            token
        });

    } catch (error) {
        // Log error for debugging
        console.log(error);

        // Send generic error response
        res.json({
            success: false,
            message: "Error during login"
        });
    }
};


// ============================================================
// JWT TOKEN GENERATOR
// ============================================================

// Purpose:
// --------
// Creates a JSON Web Token (JWT)
// - Token contains user ID as payload  from the databdse created by mongoodb automatically
// - Token is signed using secret key from .env file
//
// Why JWT?
// --------
// - Used for authentication
// - Sent from frontend in headers for protected routes
//
const createToken =  (id) =>{
    return jwt.sign(
        { id },                     // payload (user ID)
        process.env.JWT_SECRET      // secret key
    );
};


// ============================================================
// REGISTER USER CONTROLLER
// ============================================================

// Purpose:
// --------
// Registers a new user
// - Validates input data
// - Checks if user already exists
// - Hashes password before saving
// - Saves user to MongoDB
// - Generates JWT token on successful registration
//
// Request Type: POST
// Endpoint: /api/user/register
//
// Request Body:
// -------------
// {
//   "name": "John Doe",
//   "email": "john@example.com",
//   "password": "password123"
// }
//
const registerUser = async function (req, res) {

    // Extract user details from request body
    const { name, email, password } = req.body;

    // --------------------------------------------------------
    // BASIC INPUT VALIDATION
    // --------------------------------------------------------

    // Check if any required field is missing
    if (!name || !email || !password) {
        return res.status(400).json({
            success: false,
            message: "All fields are required"
        });
    }

    try {
        // ----------------------------------------------------
        // CHECK IF USER ALREADY EXISTS
        // ----------------------------------------------------

        const existingUser = await userModel.findOne({ email });

        // If user already exists, stop registration
        if (existingUser) {
            return res.status(409).json({
                success: false,
                message: "User already exists"
            });
        }

        // ----------------------------------------------------
        // VALIDATE EMAIL & PASSWORD
        // ----------------------------------------------------

        // Validate email format
        if (!validator.isEmail(email)) {
            return res.status(400).json({
                success: false,
                message: "Invalid email format"
            });
        }

        // Validate password length
        if (password.length < 8) {
            return res.status(400).json({
                success: false,
                message: "Password must be at least 8 characters"
            });
        }

        // ----------------------------------------------------
        // HASH PASSWORD
        // ----------------------------------------------------

        // Generate salt for hashing
        const salt = await bcrypt.genSalt(10);

        // Hash password with salt
        const hashedPassword = await bcrypt.hash(password, salt);

        // ----------------------------------------------------
        // SAVE USER TO DATABASE
        // ----------------------------------------------------

        const newUser = new userModel({
            name,
            email,
            password: hashedPassword // Store hashed password, NOT plain text
        });

        const savedUser = await newUser.save();

        // Debug log to confirm user is saved
        console.log("✅ User saved to DB:", savedUser);

        // ----------------------------------------------------
        // GENERATE TOKEN & SEND RESPONSE
        // ----------------------------------------------------

        const token = createToken(savedUser._id);// function make above for ge=nerate token

        res.status(201).json({
            success: true,
            message: "User registered successfully",
            token
        });

    } catch (error) {
        // Log detailed error for debugging
        console.error("❌ Error during user registration:", error);

        // Send server error response
        res.status(500).json({
            success: false,
            message: "Internal Server Error",
            error: error.message
        });
    }
};


